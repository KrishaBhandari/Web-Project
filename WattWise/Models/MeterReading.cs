using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace WattWise.Models;

/// <summary>
/// Records each monthly (or periodic) electricity meter reading for a Connection.
/// Bill amount is derived from the TariffSlab applicable to the units consumed.
/// </summary>
public class MeterReading
{
    [Key]
    public int ReadingId { get; set; }

    [Required]
    [Display(Name = "Reading Date")]
    [DataType(DataType.Date)]
    public DateTime ReadingDate { get; set; }

    [Required(ErrorMessage = "Previous reading is required.")]
    [Range(0, 9999999, ErrorMessage = "Invalid reading value.")]
    [Display(Name = "Previous Reading (kWh)")]
    public decimal PreviousReading { get; set; }

    [Required(ErrorMessage = "Current reading is required.")]
    [Range(0, 9999999, ErrorMessage = "Invalid reading value.")]
    [Display(Name = "Current Reading (kWh)")]
    public decimal CurrentReading { get; set; }

    /// <summary>Units consumed = CurrentReading - PreviousReading (computed, not stored)</summary>
    [NotMapped]
    public decimal UnitsConsumed => CurrentReading - PreviousReading;

    [Range(0, double.MaxValue)]
    [Display(Name = "Bill Amount (₹)")]
    public decimal BillAmount { get; set; }           // Calculated at the time of entry

    [Display(Name = "Is Paid")]
    public bool IsPaid { get; set; } = false;

    [DataType(DataType.Date)]
    [Display(Name = "Due Date")]
    public DateTime? DueDate { get; set; }

    [StringLength(500)]
    public string? Remarks { get; set; }

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    // ── Solar meter readings (null for non-solar connections) ─────────────────
    // Cumulative readings — period values are calculated from consecutive entries.

    /// <summary>Previous cumulative reading from the solar generation meter (kWh).</summary>
    [Range(0, 9999999)] public decimal? PrevSolarGenReading { get; set; }

    /// <summary>Current cumulative reading from the solar generation meter (kWh).</summary>
    [Range(0, 9999999)] public decimal? CurrSolarGenReading { get; set; }

    /// <summary>Previous cumulative reading from the grid export meter (kWh).</summary>
    [Range(0, 9999999)] public decimal? PrevGridExportReading { get; set; }

    /// <summary>Current cumulative reading from the grid export meter (kWh).</summary>
    [Range(0, 9999999)] public decimal? CurrGridExportReading { get; set; }

    // ── Computed solar values (not stored in DB) ──────────────────────────────

    /// <summary>kWh generated by solar panels this period. Null when meter readings unavailable.</summary>
    [NotMapped]
    public decimal? SolarGenerationKwh =>
        (CurrSolarGenReading.HasValue && PrevSolarGenReading.HasValue)
            ? CurrSolarGenReading.Value - PrevSolarGenReading.Value
            : null;

    /// <summary>kWh exported to the grid this period. Null when export meter unavailable.</summary>
    [NotMapped]
    public decimal? GridExportKwh =>
        (CurrGridExportReading.HasValue && PrevGridExportReading.HasValue)
            ? CurrGridExportReading.Value - PrevGridExportReading.Value
            : null;

    /// <summary>
    /// kWh consumed at home from solar generation this period.
    /// Only calculated when generation and export are both known AND no battery is present
    /// (battery makes the simple Gen−Export formula unreliable).
    /// </summary>
    [NotMapped]
    public decimal? SolarSelfConsumedKwh
    {
        get
        {
            if (!SolarGenerationKwh.HasValue || !GridExportKwh.HasValue)
                return null;
            // Requires no-battery assumption; controller sets this to null when HasBattery=true
            return SolarGenerationKwh.Value - GridExportKwh.Value;
        }
    }

    // Foreign key to Connection
    [ForeignKey(nameof(Connection))]
    public int ConnectionId { get; set; }
    public Connection Connection { get; set; } = null!;
}
